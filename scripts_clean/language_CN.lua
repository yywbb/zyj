function language.artifactResonanceAttr(self,artifacts)

    printT(artifacts,"artifactResonanceAttr")
    if artifacts.resonanceActiveId1 == 0 and artifacts.resonanceActiveId2 == 0 and artifacts.resonanceActiveId3 == 0 and artifacts.resonanceSkillNum < 2 then
        return ""
    end


    local attrValue = 0
    if artifacts.resonanceActiveId1 > 0 then
        attrValue = attrValue + gamedata.config.resonance_attribute["1"][tostring(artifacts.resonanceActiveId1)].attribute
    end
    
    if artifacts.resonanceActiveId2 > 0 then
        attrValue = attrValue + gamedata.config.resonance_attribute["1"][tostring(artifacts.resonanceActiveId2)].attribute
    end

    if artifacts.resonanceActiveId3 > 0 then
        attrValue = attrValue + gamedata.config.resonance_attribute["1"][tostring(artifacts.resonanceActiveId3)].attribute
    end


    --一条没有共鸣
    if artifacts.resonanceSkillNum > 1 then
        attrValue = attrValue + gamedata.config.resonance_attribute["2"][tostring(artifacts.resonanceSkillNum)].attribute
    end

    if attrValue > 0 then
        return "(共鸣速度+"..attrValue..")"
    else
        return "(神技共鸣)"
    end
end

