function language.string_format(self, keyTable, valueTable)
    local finStr
    for k, v in ipairs(keyTable) do
        finStr = finStr and finStr[v] or self[v]
    end
    if not finStr then
        return ""
    end
    if not valueTable or #valueTable == 0 then
        return finStr
    end
    for k,v in ipairs(valueTable) do
        valueTable[k] = tostring(v)
    end
    return string.format(finStr,unpack(valueTable))
end

function language.string_formatS(...)
    local argT = {...}
    return argT[1]:string_format({"fixedStringA",argT[2]},{unpack(argT,3)}) --unpack 函数5.1， 5.2及之后 table.unpack
end

