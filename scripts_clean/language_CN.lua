    return string.format("%d",timeTb.year).."/"..string.format("%02d",timeTb.month).."/"..string.format("%02d",timeTb.day).."  "..string.format("%02d",timeTb.hour)..":"..string.format("%02d",timeTb.min)..":"..string.format("%02d",timeTb.sec)
end

