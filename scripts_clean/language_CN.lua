function language.titleEndTime( self,endtime)
    
    local str = ""

    if endtime == -1 then
        str = gameConfig.strings:string_common("fixedString","mainscene",24)
    elseif endtime == 0 then
        str = gameConfig.strings:string_common("fixedString","mainscene",25)
    elseif endtime > 0 then
        if endtime >= 3600*24 then
            str = math.floor(endtime/(3600*24)).."天"
        else
            local hour = math.floor(endtime/3600)
            local min = math.floor(endtime%3600/60)
            str = string.format("%02d",hour).."小时"..string.format("%02d",min).."分"
        end
    elseif endtime < -1 then
        str = "已失效"
    end
    return str
end

