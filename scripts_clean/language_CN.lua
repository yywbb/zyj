function language.skillEffectDesc(self,skillconfig,skilllevel)

    skilllevel = skilllevel or 1
    skilllevel = math.max(skilllevel,1)
    
    local str = ""
    if skillconfig and skillconfig["effect-desc"] then
        if skillconfig["atk_param_"..skilllevel] and tonumber(skillconfig["atk_param_"..skilllevel]) then
            str = string.gsub(skillconfig["effect-desc"],"##",tonumber(skillconfig["atk_param_"..skilllevel])*100)
        else
            str = skillconfig["effect-desc"]
        end
    end
    return str
end

